def permanence_label(lang: str, value: str) -> str:
    """Etiqueta singular del estado final (``Desertor`` en lugar de ``Desertores``)."""
    return PERMANENCE_LABELS.get(lang, PERMANENCE_LABELS["es"]).get(value, value)


def status_label(lang: str, value: str) -> str:
    return STATUS_LABELS.get(lang, STATUS_LABELS["es"]).get(value, value)


def signal_label(lang: str, value: str) -> str:
    """Traduce los prefijos de las señales generadas por el motor de riesgo."""
    if lang != "en":
        return value
    for source, target in SIGNAL_PREFIXES["en"].items():
        if value.startswith(source):
            return target + value[len(source):]
    return value


def fmt_int(value, lang: str = "es") -> str:
    text = f"{int(value):,}"
    return text.replace(",", ".") if lang == "es" else text


def fmt_pct(value, lang: str = "es") -> str:
    text = f"{float(value):.1f}%"
    return text.replace(".", ",") if lang == "es" else text
